# Какие стили подходят к каким видам постов (первые предпочтительнее).
FOR_KIND = {
    "news": ["cards", "list", "story"],
    "brawler": ["proscons", "list", "cards", "story"],
    "fact": ["didyouknow", "quiz", "story", "cards"],
    "top": ["rating", "list"],
    "tip": ["list", "story", "cards", "proscons"],
    "poll": ["cards", "story", "list"],
}


def pick_style(kind, recent):
    """Стиль для поста: подходящий к виду и не такой, как у последних постов."""
    options = FOR_KIND.get(kind, list(STYLES))
    fresh = [s for s in options if s not in recent[-2:]] or options
    return random.choice(fresh[:3])


def style_prompt(style):
    return STYLES.get(style, STYLES["cards"])


